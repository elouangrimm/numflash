// Extracts the pieces we need out of NumWorks' webpack bundle (app-loader.js):
//   - the two Emscripten glue modules (GNU ld and objcopy compiled to WASM)
//   - eadk.o (the EADK syscall stubs every .nwa is linked against)
//   - the linker-script template
// Usage: node scripts/extract-vendor.mjs path/to/app-loader.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/extract-vendor.mjs app-loader.js'); process.exit(1); }
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'js', 'vendor');
const lines = fs.readFileSync(src, 'utf8').split('\n');

// Webpack modules sit at 12-space indent: "            12345: function(".
const starts = [];
lines.forEach((l, i) => { const m = l.match(/^ {12}(\d+): function/); if (m) starts.push([+m[1], i]); });
const body = (id) => {
  const k = starts.findIndex(([n]) => n === id);
  if (k < 0) throw new Error('module ' + id + ' not found');
  const end = k + 1 < starts.length ? starts[k + 1][1] : lines.length;
  return lines.slice(starts[k][1], end).join('\n').replace(/,\s*$/, '');
};
// "12345: function(e,t,r){...}"  ->  "function(e,t,r){...}"
const fnSource = (id) => body(id).replace(/^\s*\d+:\s*/, '');

// ---- Emscripten glue (ld = 48148, objcopy = 85552) ----------------------
function glue(id, name) {
  const code = fnSource(id);
  const js = `// ${name} Emscripten glue, extracted from NumWorks' app-loader bundle (module ${id}).
// Auto-generated by scripts/extract-vendor.mjs. Do not edit.
const stubRequire = () => ({});
const mod = { exports: {} };
(${code})(mod, mod.exports, stubRequire);
export default mod.exports;
`;
  fs.writeFileSync(path.join(out, name + '-glue.js'), js);
  console.log('wrote', name + '-glue.js', js.length);
}
glue(48148, 'ld');
glue(85552, 'objcopy');

// ---- eadk.o -------------------------------------------------------------
{
  const m = { exports: null };
  new Function('e', '(' + fnSource(30786) + ')(e)')(m);
  const bytes = Buffer.from(m.exports.data);
  fs.writeFileSync(path.join(out, 'eadk-o.js'),
    `// eadk.o from NumWorks' app-loader bundle (module 30786). Auto-generated.\n` +
    `const b64 = '${bytes.toString('base64')}';\n` +
    `export const EADK_O = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));\n`);
  console.log('wrote eadk-o.js', bytes.length, 'bytes');
}

// ---- linker script template --------------------------------------------
{
  let text = null;
  const stub = { Template: class { constructor(_c, t) { text = t; } render() { return ''; } } };
  const mod = { exports: null };
  new Function('e', 't', 'r', '(' + fnSource(89698) + ')(e,t,r)')(mod, {}, () => stub);
  mod.exports();   // building the Template captures the source text
  if (!text) throw new Error('could not read linker template');
  fs.writeFileSync(path.join(out, 'linker-script.js'),
    `// Linker script template from NumWorks' app-loader bundle (module 89698). Auto-generated.\n` +
    `const TEMPLATE = ${JSON.stringify(text)};\n` +
    `export function renderLinkerScript(ctx) {\n` +
    `  return TEMPLATE.replace(/\\{\\{\\s*(\\w+)\\s*\\}\\}/g, (_, k) => {\n` +
    `    if (!(k in ctx)) throw new Error('linker script: missing ' + k);\n` +
    `    return String(ctx[k]);\n  });\n}\n`);
  console.log('wrote linker-script.js', text.length, 'chars');
}
